def proofread(title: str, sections: list[str]) -> tuple[str, str]:
    """맞춤법·오타만 고치는 교정 요청."""
    import json as _json
    system = """너는 한국어 블로그 글 교정자야. 맞춤법, 오타, 띄어쓰기, 문맥상 잘못 쓴 단어(예: '연속 온수'를 '연속 온실'로 쓴 것)만 고쳐.
- 내용, 말투, 이모지, 기호, 줄바꿈, 문단, 순서, 숫자, 가격, 상품명, 링크, [구매링크] 같은 표시는 그대로 둬
- 문장을 새로 쓰거나 다듬지 말고, 틀린 글자만 바꿔
- 섹션 개수와 순서는 반드시 그대로
- JSON만 출력: {"title": "...", "sections": ["...", ...], "fixes": ["고친 것 짧게", ...]}"""
    user = _json.dumps({"title": title, "sections": sections}, ensure_ascii=False)
    return system, user


